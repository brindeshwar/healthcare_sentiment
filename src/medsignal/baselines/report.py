"""Combine baseline outputs into ``reports/baselines/metrics.json`` and a generated README table.

Usage:
    uv run python -m medsignal.baselines.report
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

from medsignal.baselines.classical import EVAL_SPLITS
from medsignal.evaluation.metrics import mean_std
from medsignal.utils import PROJECT_ROOT, git_sha

log = logging.getLogger(__name__)

METRICS = ("macro_f1", "accuracy", "qwk")


def aggregate(classical: dict[str, Any], encoder_runs: list[dict[str, Any]]) -> dict[str, Any]:
    """One row per (model, split): metric -> {mean, std, n_runs}."""
    rows: dict[str, Any] = {}
    for model in ("majority", "tfidf_logreg"):
        rows[model] = {
            sp: {m: mean_std([classical[model][sp]], m) for m in METRICS} for sp in EVAL_SPLITS
        }
    if encoder_runs:
        rows["encoder"] = {
            sp: {m: mean_std([r[sp] for r in encoder_runs], m) for m in METRICS}
            for sp in EVAL_SPLITS
        }
        rows["encoder"]["seeds"] = sorted(r["seed"] for r in encoder_runs)
        rows["encoder"]["reviews_per_second_test"] = mean_std(
            [r["test"] for r in encoder_runs], "reviews_per_second"
        )
    return rows


def _cell(x: dict[str, float]) -> str:
    return f"{x['mean']:.3f} ± {x['std']:.3f}" if x["n_runs"] > 1 else f"{x['mean']:.3f}"


def write_readme(agg: dict[str, Any], classical: dict[str, Any], path: Path, sha: str) -> None:
    names = {
        "majority": "Majority class",
        "tfidf_logreg": "TF-IDF + logistic regression",
        "encoder": "BioClinical ModernBERT (fine-tuned)",
    }
    lines = [
        "# Sentiment baselines (generated)",
        "",
        "> Generated by `uv run python -m medsignal.baselines.report` from the JSON files in this folder.",
        f"> Commit `{sha}`. Sanity baselines only (ADR-0010); the project's headline task is ADE extraction.",
        "",
        f"Task: {classical['task']}. Model selection on `val`; `test` = seen drugs, `drug_holdout` = unseen drugs (ADR-0013).",
        "Encoder: mean ± sample std over seeds.",
        "",
        "| Model | Split | Macro-F1 | Accuracy | QWK |",
        "|---|---|---|---|---|",
    ]
    for model, label in names.items():
        if model not in agg:
            continue
        for sp in ("test", "drug_holdout"):
            r = agg[model][sp]
            lines.append(
                f"| {label} | {sp} | {_cell(r['macro_f1'])} | {_cell(r['accuracy'])} | {_cell(r['qwk'])} |"
            )
    leak = classical["leakage_demo"]
    legacy, control = leak["legacy_with_duplicates"], leak["control_deduplicated"]
    lines += [
        "",
        "## Duplicate leakage (why the legacy score was inflated)",
        "",
        f"{leak['description']}. Same data and procedure; only de-duplication differs.",
        "",
        "| Setup | Reviews | Test reviews also in train | Macro-F1 | Accuracy |",
        "|---|---|---|---|---|",
        f"| Legacy (duplicates kept) | {legacy['rows']:,} | {legacy['test_reviews_whose_text_is_in_train']:.1%} | "
        f"{legacy['test']['macro_f1']:.3f} | {legacy['test']['accuracy']:.3f} |",
        f"| De-duplicated control | {control['rows']:,} | {control['test_reviews_whose_text_is_in_train']:.1%} | "
        f"{control['test']['macro_f1']:.3f} | {control['test']['accuracy']:.3f} |",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    folder = PROJECT_ROOT / "reports" / "baselines"
    classical = json.loads((folder / "classical.json").read_text(encoding="utf-8"))
    runs = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted(folder.glob("encoder_seed*.json"))
        if "smoke" not in p.name
    ]
    agg = aggregate(classical, runs)
    sha = git_sha()
    agg["meta"] = {"git_sha": sha, "encoder_runs": len(runs)}
    (folder / "metrics.json").write_text(
        json.dumps(agg, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    write_readme(agg, classical, folder / "README.md", sha)
    log.info("aggregated %s encoder runs", len(runs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
