"""Phase 3 comparison table: LLM teacher vs encoder student vs zero-shot GLiNER-BioMed on CADEC.

Usage:
    uv run python -m medsignal.extraction.report --config configs/student.yaml

Reads ``reports/teacher/cadec_*/`` (chosen teacher), ``reports/student/seed*.json`` and
``reports/student/gliner_biomed.json``; writes ``reports/student/comparison.json`` and README.md.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from medsignal.evaluation.metrics import mean_std
from medsignal.labeling.benchmark import safe_name
from medsignal.utils import PROJECT_ROOT, git_sha, load_config


def _read(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def build(cfg: dict[str, Any]) -> dict[str, Any]:
    teacher_cfg = load_config(cfg["teacher_config"])
    t = teacher_cfg["teacher"]
    rows: dict[str, Any] = {}
    for split in ("dev", "test"):
        tr = _read(
            PROJECT_ROOT
            / teacher_cfg["report_dir"]
            / f"cadec_{split}"
            / f"{safe_name(t['model'])}__{t['prompt']}.json"
        )
        if tr:
            m = tr["metrics"]
            rows.setdefault("teacher", {})[split] = {
                "relaxed_f1": m["relaxed"]["f1"],
                "relaxed_ci": [m["relaxed"]["f1_lo"], m["relaxed"]["f1_hi"]],
                "relaxed_p": m["relaxed"]["precision"],
                "relaxed_r": m["relaxed"]["recall"],
                "strict_f1": m["strict"]["f1"],
                "docs_per_second": round(1 / m["seconds_median"], 2)
                if m["seconds_median"]
                else None,
            }
    report_dir = PROJECT_ROOT / cfg["report_dir"]
    seeds: list[dict[str, Any]] = [
        s
        for p in sorted(report_dir.glob("seed*.json"))
        if "smoke" not in p.name and (s := _read(p)) is not None
    ]
    if seeds:
        rows["student"] = {}
        for split in ("dev", "test"):
            ms = [s[f"cadec_{split}"] for s in seeds]
            rows["student"][split] = {
                "relaxed_f1": mean_std([m["relaxed"] for m in ms], "f1"),
                "relaxed_p": mean_std([m["relaxed"] for m in ms], "precision"),
                "relaxed_r": mean_std([m["relaxed"] for m in ms], "recall"),
                "strict_f1": mean_std([m["strict"] for m in ms], "f1"),
                "docs_per_second": mean_std(ms, "docs_per_second"),
            }
        rows["student"]["seeds"] = [s["seed"] for s in seeds]
    gl = _read(report_dir / "gliner_biomed.json")
    if gl:
        rows["gliner"] = {
            split: {
                "relaxed_f1": gl[f"cadec_{split}"]["relaxed"]["f1"],
                "relaxed_ci": [
                    gl[f"cadec_{split}"]["relaxed"]["f1_lo"],
                    gl[f"cadec_{split}"]["relaxed"]["f1_hi"],
                ],
                "relaxed_p": gl[f"cadec_{split}"]["relaxed"]["precision"],
                "relaxed_r": gl[f"cadec_{split}"]["relaxed"]["recall"],
                "strict_f1": gl[f"cadec_{split}"]["strict"]["f1"],
            }
            for split in ("dev", "test")
        }
        rows["gliner"]["chosen_on_dev"] = gl["chosen"]
    rows["meta"] = {"teacher": t, "student_model": cfg["model"], "git_sha": git_sha()}
    return rows


def _v(x: Any) -> str:
    if isinstance(x, dict):
        return f"{x['mean']:.3f} ± {x['std']:.3f}"
    return f"{x:.3f}"


def write_readme(rows: dict[str, Any], path: Path) -> None:
    lines = [
        "# ADE extraction on CADEC: teacher vs student vs zero-shot baseline (generated)",
        "",
        "> Generated by `uv run python -m medsignal.extraction.report`. Expert gold: CADEC (ADR-0018).",
        "> Student = BioClinical ModernBERT trained only on the teacher's silver labels of Drugs.com reviews",
        "> (mean ± std over seeds). Teacher/GLiNER: point estimate [95% bootstrap CI]. Test used once.",
        "",
        "| System | Split | Relaxed P | Relaxed R | **Relaxed F1** | Strict F1 | Docs/s |",
        "|---|---|---|---|---|---|---|",
    ]
    names = {
        "teacher": f"LLM teacher `{rows['meta']['teacher']['model']}` ({rows['meta']['teacher']['prompt']})",
        "student": "Encoder student (BioClinical ModernBERT)",
        "gliner": "GLiNER-BioMed large, zero-shot",
    }
    for split in ("test", "dev"):
        for key, label in names.items():
            r = rows.get(key, {}).get(split)
            if not r:
                continue
            f1 = _v(r["relaxed_f1"]) + (
                f" [{r['relaxed_ci'][0]:.3f}, {r['relaxed_ci'][1]:.3f}]"
                if "relaxed_ci" in r
                else ""
            )
            dps = r.get("docs_per_second")
            dps_s = (
                (f"{dps['mean']:.0f}" if isinstance(dps, dict) else f"{dps:.1f}") if dps else "n/a"
            )
            lines.append(
                f"| {label} | {split} | {_v(r['relaxed_p'])} | {_v(r['relaxed_r'])} | **{f1}** | {_v(r['strict_f1'])} | {dps_s} |"
            )
    lines += ["", f"Commit `{rows['meta']['git_sha']}`.", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="configs/student.yaml")
    args = parser.parse_args(argv)
    cfg = load_config(args.config)
    rows = build(cfg)
    out = PROJECT_ROOT / cfg["report_dir"]
    (out / "comparison.json").write_text(
        json.dumps(rows, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    write_readme(rows, out / "README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
